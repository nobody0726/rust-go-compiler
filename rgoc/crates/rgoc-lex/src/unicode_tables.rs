//!
//! # 生成方式
//!
//! ```text
//! RGOC_TTY=0 scripts/in-container.sh bash -lc \
//!   'cd /work/tools/token-oracle && go run ./gen_unicode /work/rgoc/crates/rgoc-lex/src/unicode_tables.rs'
//! ```
//!
//! 生成器：tools/token-oracle/gen_unicode/main.go（约 100 行，可读）。
//! **要改这个文件就得改生成器** —— 手改会在下次再生成时被覆盖，
//! 而且会破坏「表 == oracle 的区间，一条不多一条不少」这条可校验性。
//!
//! # 为什么不用 Rust std 的近似谓词
//!
//! 官方 scanner 用的是 unicode.IsLetter / unicode.IsDigit（导出面用 unicode.IsUpper），
//! 而 Rust std：
//!
//! | 谓词 | Go（oracle） | Rust std | 差异 |
//! |---|---|---|---|
//! | 字母 IsLetter(L*) | 145672 码点 | is_alphabetic 147,421 | **多 1,749**（全是 Mn 组合符） |
//! | 数字 IsDigit(Nd) | 770 码点 | is_numeric 1,924 | **多 1,154**（全是 No） |
//! | 大写 IsUpper(Lu) | 1886 码点 | is_uppercase 2,006 | **多 120**（5 段，全是 Other_Uppercase） |
//!
//! 差异是**静默的**，但**不在词元边界上** —— 边界通常相同。
//!
//! 官方 `atIdentChar` 对「不是字母、也不是 Nd」的非 ASCII 字符是
//! **报错但仍然吸收**（`case s.ch >= utf8.RuneSelf: s.errorf(…);` 之后 `return true`），
//! 所以 `x²` 在 Go 里是**一个** `name` **外加一条** `LEX-BAD-IDENT-CHAR`。
//! 而用 Rust std 的近似谓词时 `²` 被当成数字 ⇒ **不报错** ⇒ **少一条诊断**；
//! 起始位置（`²abc`）还会给出**不同的代号**。
//!
//! | 输入 | Go 的词元 | Go 的诊断 | std 近似谓词 |
//! |---|---|---|---|
//! | `x²`（U+00B2，No） | `name "x\xc2\xb2"` | `LEX-BAD-IDENT-CHAR` @1:2 | `is_numeric`=true ⇒ **静默通过** |
//! | `²abc` | `name "\xc2\xb2abc"` | `LEX-BAD-IDENT-CHAR` @1:1 | 报成 `LEX-ID-LEADING-DIGIT`（**代号不同**） |
//! | `x\u{0345}`（Mn） | `name "x\xcc\x85"` | `LEX-BAD-IDENT-CHAR` @1:2 | `is_alphabetic`=true ⇒ **静默通过** |
//! | `xµ`（U+00B5，Ll） | `name "x\xc2\xb5"` | **无** | 一致（对照组） |
//! | `x１`（U+FF11，Nd） | `name "x\xef\xbc\x91"` | **无** | 一致（对照组） |
//!
//! **少一条诊断比「词元切错」更难发现** —— 这正是表必须由 oracle 生成的原因。
//!
//! # 表的内容边界
//!
//! 三张表**严格等于** unicode.IsLetter / unicode.IsDigit / unicode.IsUpper 的区间：
//!
//! - **不含代理区**（U+D800..U+DFFF）—— 它不是标量值，char 造不出来
//! - **只有 LETTER_RANGES 需要补下划线 U+005F** —— 见 is_letter 的说明
//!   （`is_upper('_')` 是 false，与 Go 一致：`_` 不是大写）
//!
