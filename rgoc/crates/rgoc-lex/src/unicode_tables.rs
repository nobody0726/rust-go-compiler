/// 是否算「字母」—— 对应官方 scanner.atIdentChar 的第一个 case。
///
/// # 下划线为什么在这里而不是在表里
///
/// Go 规范的 letter = unicode_letter | "_" 把下划线**算作字母**；
/// 官方 isLetter() 也就是 ASCII 字母 || '_'。但 Unicode **没有**把它归入 L* ——
/// 所以它不在生成表里，而是由本函数补上。
///
/// 这样只要往 LETTER_RANGES 里多塞一个 (0x005F, 0x005F)，测试里的两条断言立刻会红
/// —— 表能逐字对着 oracle 校验：「== unicode.IsLetter 的区间，一条不多一条不少」。
#[inline]
pub fn is_letter(c: char) -> bool {
    c == '_' || lookup(LETTER_RANGES, c)
}

/// 是否是「十进制数字」（Unicode 类别 Nd）—— 对应 atIdentChar 的第二个 case。
///
/// 注意**不是** N*：² ¼ 这类上标/分数（No）不算，它们是非法标识符字符。
#[inline]
pub fn is_digit(c: char) -> bool {
    lookup(DIGIT_RANGES, c)
}

/// 是否是「大写字母」（Unicode 类别 Lu）—— 官方导出标识符判定的那一位。
///
/// 对应 `go/token.IsExported`：
///
/// ```go
/// func IsExported(name string) bool {
///     ch, _ := utf8.DecodeRuneInString(name)
///     return unicode.IsUpper(ch)   // 首码点，不是「名字里有没有大写」
/// }
/// ```
///
/// # 为什么不用 Rust std 的 `char::is_uppercase`
///
/// std 的是 **derived `Uppercase`** 属性 = Lu ∪ **Other_Uppercase**，实测多 120 个码点
/// （5 段，全部是 Nl / So 的「带圈/带框/罗马数字」）：
///
/// | 区间 | 码点 | 例子 |
/// |---|---|---|
/// | U+2160..U+216F | 16 | Ⅰ（罗马数字一，Nl） |
/// | U+24B6..U+24CF | 26 | Ⓐ（带圈，So） |
/// | U+1F130..U+1F149 | 26 | 🄰（带框，So） |
/// | U+1F150..U+1F169 | 26 | 🅐（反白，So） |
/// | U+1F170..U+1F189 | 26 | 🅰（方块，So） |
///
/// 后果：`Ⅰx` 在 Go 里**不导出**，用 std 就判成导出 —— 而导出判定是**导出面**
/// （`ExportSummary` / 跨包可见性）的输入，错一个码点就是错一个 API 表面。
/// 与 M1 的两张表同一个理由（D-M1-6）：**表由 oracle 生成**。
#[inline]
pub fn is_upper(c: char) -> bool {
    lookup(UPPER_RANGES, c)
}

/// 在升序、互不重叠的区间表里二分查找。
///
/// 比较器的方向容易写反：binary_search_by 的闭包接收的是**表里的元素**，
/// 要返回的是「该元素相对**目标**的大小」（元素区间整体落在目标之下 ⇒ Less）。
fn lookup(table: &[(u32, u32)], c: char) -> bool {
    let cp = c as u32;
    table
        .binary_search_by(|&(lo, hi)| {
            if hi < cp {
                core::cmp::Ordering::Less
            } else if lo > cp {
                core::cmp::Ordering::Greater
            } else {
                core::cmp::Ordering::Equal
            }
        })
        .is_ok()
}
