#[test]
fn errorcheck_同前缀的多余诊断_判失败() {
    // ⚠️ 官方**不允许**忽略没被任何期望命中的诊断：没命中的会**放回池子**（`:1272`），
    // 最后池子非空 ⇒ `Unmatched Errors`（`:1281-1304`）。
    // 我最初把这里写反了（以为「同前缀的多余诊断可以忽略」）—— 那样会漏判真失败。
    let want = wanted_errors(
        "package main\nfunc f() {\n\tm() // ERROR \"undefined: m\"\n}\n",
        "x.go",
    )
    .unwrap();
    let out = format!(
        "{}\n{}\n",
        diag(3, "undefined: m"),
        diag(3, "missing return")
    );
    let errs = error_check(&out, &want).unwrap_err();
    assert!(
        errs.iter().any(|e| e.contains("Unmatched")),
        "同前缀却没被命中的诊断必须算失败，实际：{errs:?}"
    );
}

#[test]
fn errorcheck_一个期望_覆盖同一行两条诊断() {
    // T-C-19 typecheck.go 实测是 5 条诊断配 4 条期望 —— 能过的原因是
    // **每条诊断都被某条期望命中**（不是「允许剩一条」）。这里用交替模式复现。
    let want = wanted_errors(
        "package main\nfunc f() {\n\tm() // ERROR \"undefined: m|missing return\"\n}\n",
        "x.go",
    )
    .unwrap();
    let out = format!(
        "{}\n{}\n",
        diag(3, "undefined: m"),
        diag(3, "missing return")
    );
    let r = error_check(&out, &want);
    assert!(r.is_ok(), "交替模式应当同时覆盖两条诊断（{:?}）", r.err());
}

