#[test]
fn r3_制表符开头_续行拼到上一条() {
    let out = "a.go:3:2: first problem\n\tb.go:4:1: detail one\n\tb.go:5:1: detail two\n";
    let got = split_output(out, false);
    assert_eq!(got.len(), 1, "续行应拼进同一条：{got:?}");
    assert_eq!(got[0].lines().count(), 3, "拼进去后是 3 行");
    assert!(got[0].contains("detail one") && got[0].contains("detail two"));
}

#[test]
fn r3_跳过_go_tool_井号_与_autogenerated() {
    // :1206 —— 以 "go tool" / "#" / "<autogenerated>" 开头的行跳过
    let out = "# command-line-arguments\ngo tool compile -V=full\nx.go:1:1: real\n";
    assert_eq!(split_output(out, false), vec!["x.go:1:1: real".to_string()]);
    // wantAuto 为真时 <autogenerated> **不**跳过（GC_ERRORAUTO 用它）
    let out2 = "<autogenerated>:1:1: from autogenerated\nx.go:1:1: real\n";
    assert_eq!(
        split_output(out2, true).len(),
        2,
        "want_auto 时要保留 autogenerated 行"
    );
    assert_eq!(
        split_output(out2, false).len(),
        1,
        "默认丢掉 autogenerated 行"
    );
}

#[test]
fn r3_跳过纯空白行() {
    // :1208
    // 只用空格与空行 —— 单独一个 "\t" 行在官方语义里是**续行**，会拼进上一条
    let out = "a.go:1:1: one\n   \n\nb.go:2:1: two\n";
    assert_eq!(
        split_output(out, false),
        vec!["a.go:1:1: one".to_string(), "b.go:2:1: two".to_string()]
    );
}

#[test]
fn r3_去掉行尾_cr() {
    // :1201-1202 —— 兼容 Windows 上编译器的 \r
    assert_eq!(
        split_output("a.go:1:1: one\r\n", false),
        vec!["a.go:1:1: one".to_string()]
    );
}

