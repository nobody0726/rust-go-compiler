#[test]
fn r2_两种不匹配的措辞不同() {
    // :1186-1190 —— 有 .out 说「内容不符」，无 .out 说「本应为空」
    let with = check_expected_output("x\n", Some("y\n")).unwrap_err();
    assert!(
        with.to_string().contains("不匹配"),
        "有 .out 时的措辞：{with}"
    );
    let without = check_expected_output("x\n", None).unwrap_err();
    assert!(
        without.to_string().contains("本应为空"),
        "无 .out 时的措辞：{without}"
    );
    // 两种措辞必须能区分开（官方就是靠这个告诉人「是输出错了」还是「本该静默」）
    assert_ne!(with.to_string(), without.to_string());
}

