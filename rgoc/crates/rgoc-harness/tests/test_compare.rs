#[test]
fn r4_line_占位符_折算成绝对行号() {
    // :1466-1476 —— LINE / LINE+n / LINE-n 替换为 <short>:<绝对行号>
    let src = "package main\nfunc main() {\n\t_ = 1\n\t_ = 2 // ERROR \"LINE:[^\\n]*\" LINE:3 \"LINE+1:[^\\n]*\"\n}\n";
    let errs = wanted_errors(src, "x.go").expect("应能解析");
    assert_eq!(errs.len(), 2, "两条期望");
    // ERROR 注释在第 4 行（package main / func main() { / _ = 1 / _ = 2 // ERROR）
    assert_eq!(errs[0].re_str, "x.go:4:[^\\n]*", "裸 LINE 指向本行");
    assert_eq!(errs[1].re_str, "x.go:5:[^\\n]*", "LINE+1 指向下一行");
}

