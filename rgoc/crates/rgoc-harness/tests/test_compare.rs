// ══ 正则子集：够用即止，但**不认识就报错**══════════════════════════════════

#[test]
fn matcher_子集内的构造() {
    // 字面量
    assert!(
        unanchored_match(
            "too many arguments",
            "invalid operation: too many arguments for f"
        )
        .unwrap()
    );
    // 交替
    assert!(unanchored_match("compos|conver", "composite literal uses unkeyed fields").unwrap());
    assert!(unanchored_match("conver|incompatible|cannot", "incompatible types").unwrap());
    // .* 跨行（官方用 .* 跨多行匹配续拼的诊断）
    assert!(
        unanchored_match(
            "a refers to b\n.*b refers to c",
            "a refers to b\n\tpkg.go:9: b refers to c"
        )
        .unwrap()
    );
    // 转义：\. 匹配字面点
    assert!(
        unanchored_match(
            r"undefined.*runtime\.init",
            "undefined: runtime.init (type name too long)"
        )
        .unwrap()
    );
    // 转义：\\ 匹配字面反斜杠
    assert!(unanchored_match(r"a\\b", r"path\to\a\b").unwrap());
    // 不匹配时返回 Ok(false)，不是 Err
    assert!(!unanchored_match("undefined", "all good").unwrap());
}

#[test]
fn matcher_不支持的构造_明确报错() {
    // 语料里有 5435 条模式用到 {n,m} [ ] ( ) + ? ^ $ ——
    // 本实现**不认识**它们时必须报错，绝不能静默当成「不匹配」，
    // 否则那 5435 条里的多数会被误判成「编译器有 bug」。
    for bad in [
        "a+b",    // +
        "ab?c",   // ?
        "[abc]",  // 字符类
        "(ab)c",  // 分组
        "a{2,3}", // 计数
        "^abc",   // 行首锚
        "abc$",   // 行尾锚
    ] {
        let r = unanchored_match(bad, "abc");
        assert!(
            r.is_err(),
            "不支持的构造 {bad:?} 应当报错，而不是静默返回不匹配（实际 {:?}）",
            r
        );
    }
}

#[test]
fn matcher_空模式匹配一切() {
    // 正则语义：空模式匹配任意字符串
    assert!(unanchored_match("", "anything").unwrap());
}
