//! T35 的验收测试：比较器与诊断切分（R2 / R3 / R4）。
//!
//! 规则来源全部标注 `testdir_test.go` 的行号：
//! - `checkExpectedOutput`（`:1172-1193`）—— R2
//! - `splitOutput`（`:1195-1213`）—— R3
//! - `wantedErrors`（`:1440-1499`）与 `errorCheck`（`:1249-1304`）—— R4
//! - `replacePrefix`（`:2059-2072`）
//!
//! # 正则的范围（重要）
//!
//! 顶层 `test/` 的 ERROR 模式共 **5435 条**，用到了 `{n,m}` / `[...]` / `+` / `?` / `^` / `$`
//! 等全套 Go 正则 —— 自己实现一套正则引擎不现实（那是另一个项目，且错得很安静）。
//! 而 **E4 冻结的 20 个样本只需要「字面量 + `|` + `.` / `.*` + `\` 转义」**。
//!
//! 所以本模块实现这个**子集**，遇到子集外的构造（`+` `?` `[` `(` `{` `^` `$`）**明确报错**，
//! 由上层判 `harness-failure` —— **绝不静默当成「不匹配」**，那会让 5435 条里的绝大多数
//! 用例被误判为「编译器有 bug」。
//!
//! TDD 位置：**RED**。T35 实现前本文件编译不过（`rgoc_harness::compare` 尚不存在）。

use rgoc_harness::compare::{
    OutputMismatch, check_expected_output, error_check, replace_prefix, split_output,
    unanchored_match, wanted_errors,
};

